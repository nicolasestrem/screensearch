// One definition of the service worker's cache version, shared by the stamp and the DOM gate so the
// two can never disagree about what the payload hash covers.
//
// The worker serves everything under assets/ cache-first, which is what makes a second visit instant
// and an offline visit possible, but it also hides a changed pack from anyone who already loaded the
// page. The version therefore has to move whenever the served payload moves.
//
// assets/manifest.json records paths and metadata only: no payload digest, and a rebuild can change
// textures, materials, normals or interior vertex positions without touching the triangle counts and
// bounds the manifest does record. So the manifest bytes are hashed together with the bytes of every
// pack it names, in path order, and a missing pack fails loudly rather than silently shortening the
// fingerprint.

import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

export const CACHE_VERSION_LINE = /^const CACHE_VERSION = '([^']*)';$/m;

// Payload the worker precaches and serves cache-first that is not named by the manifest. The
// opening sample is generated by tools/gen-sample.mjs, so it can change with every pack untouched;
// without its bytes in the hash a returning visitor keeps opening the previous day.
const EXTRA_PAYLOAD = ['sample-export.json'];

export async function computeCacheVersion(root) {
  const manifest = await readFile(join(root, 'assets', 'manifest.json'));
  const hash = createHash('sha256').update(manifest);
  const parsed = JSON.parse(manifest.toString('utf8'));
  const packs = (Array.isArray(parsed.packs) ? parsed.packs : []).slice();
  packs.sort(function (a, b) {
    return String(a && a.file) < String(b && b.file) ? -1 : 1;
  });
  for (let i = 0; i < packs.length; i += 1) {
    const rel = packs[i] && packs[i].file ? String(packs[i].file) : '';
    if (rel === '') continue;
    const bytes = await readFile(join(root, rel));
    // The path goes in too, so renaming a pack moves the version even with identical bytes.
    hash.update(rel);
    hash.update(bytes);
  }
  for (let i = 0; i < EXTRA_PAYLOAD.length; i += 1) {
    const rel = EXTRA_PAYLOAD[i];
    const bytes = await readFile(join(root, rel));
    hash.update(rel);
    hash.update(bytes);
  }
  return 'm' + hash.digest('hex').slice(0, 8);
}
