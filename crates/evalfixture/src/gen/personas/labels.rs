//! Localized window-chrome labels for the persona generator.
//!
//! The generated screens show menus, sidebars, status bars and the taskbar in the persona's
//! language, so a persona's environment is not just an English-language skin. Programs keep
//! their well-known names (Excel, Numbers, Word, Chrome); the words *around* them are
//! localized here. The table is a data catalog: adding a language later is one more `Labels`
//! constant plus one persona definition that points at it.
//!
//! `date_format`/`time_format` are chrono format strings for the taskbar clock and for
//! dates printed inside documents and file listings.

/// Localized UI words for one language (or one language variant, where the date format
/// differs - `en-US` writes `09/07/2026`, `en-GB` writes `07/09/2026`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Labels {
    /// Base language code (before the region): must match the persona's language tag.
    pub lang: &'static str,
    /// The language's own name, used in the catalogue listing only.
    pub name: &'static str,
    pub file: &'static str,
    pub edit: &'static str,
    pub view: &'static str,
    pub insert: &'static str,
    pub format: &'static str,
    pub tools: &'static str,
    pub help: &'static str,
    pub search: &'static str,
    pub inbox: &'static str,
    pub sent: &'static str,
    pub drafts: &'static str,
    pub archive: &'static str,
    pub documents: &'static str,
    pub downloads: &'static str,
    pub desktop: &'static str,
    pub pictures: &'static str,
    pub music: &'static str,
    pub home: &'static str,
    pub settings: &'static str,
    pub new: &'static str,
    pub open: &'static str,
    pub save: &'static str,
    pub print: &'static str,
    pub page: &'static str,
    pub of: &'static str,
    pub slide: &'static str,
    pub items: &'static str,
    /// Taskbar/document date format.
    pub date_format: &'static str,
    /// Clock format.
    pub time_format: &'static str,
}

